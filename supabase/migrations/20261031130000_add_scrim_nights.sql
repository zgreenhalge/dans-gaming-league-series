-- Weekly scrim nights: an admin-set recurring slot (`scrim_schedule`), the per-date nights players sign
-- up for (`scrim_nights`), and the signups themselves (`scrim_signups`). See docs/architecture.md.

-- Singleton (`id` pinned to 1): the one recurring weekly slot. `weekday` is 0 = Sunday … 6 = Saturday,
-- and `start_time` is wall-clock time in `timezone` (an IANA name), so the slot keeps its local time
-- across DST changes.
create table public.scrim_schedule (
  id smallint primary key default 1 check (id = 1),
  weekday smallint not null check (weekday between 0 and 6),
  start_time time not null,
  timezone text not null,
  enabled boolean not null default true
);

-- One row per scrim date that has been signed up for or cancelled; a scheduled date with neither has
-- no row. `night_date` is the calendar date in `scrim_schedule.timezone`, and the night starts at
-- `scrim_schedule.start_time` on it.
create table public.scrim_nights (
  id integer primary key generated by default as identity,
  night_date date not null unique,
  cancelled boolean not null default false
);

create table public.scrim_signups (
  id integer primary key generated by default as identity,
  night_id integer not null references public.scrim_nights(id) on delete cascade,
  player_id integer not null references public.players(id) on delete cascade,
  commitment text not null check (commitment in ('definite', 'maybe')),
  signed_up_at timestamptz not null default now(),
  unique (night_id, player_id)
);
create index scrim_signups_player_id_idx on public.scrim_signups using btree (player_id);

alter table public.scrim_schedule enable row level security;
alter table public.scrim_nights enable row level security;
alter table public.scrim_signups enable row level security;

create constraint trigger bump_data_version after insert or update or delete on public.scrim_schedule
  deferrable initially deferred for each row execute function public.bump_data_version();
create constraint trigger bump_data_version after insert or update or delete on public.scrim_nights
  deferrable initially deferred for each row execute function public.bump_data_version();
create constraint trigger bump_data_version after insert or update or delete on public.scrim_signups
  deferrable initially deferred for each row execute function public.bump_data_version();
